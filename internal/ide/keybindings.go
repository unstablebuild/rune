// keybindingsWidth is the fixed width of the key bindings floating
// window. Wider than cheatsheetWidth because entries carry a key, a
// command line, and a full manual summary on one line; the window
// manager clamps it on smaller terminals.
const keybindingsWidth = 150

// keyBindingCategory groups bindings into a titled, documented section
// by whitelisting command matchers. An entry may span several tokens
// ("lsp diagnostics"): leading tokens match argv exactly and the final
// token by prefix. Categories are rendered in declaration order; the
// final catch-all (nil Prefixes) collects every binding no category
// claimed.
type keyBindingCategory struct {
	Title    string
	Doc      string
	Prefixes []string
}

