// keyBindingAction resolves a binding's description: a whitelist
// override matched against the bound command line first and its alias
// expansion second (so aliases can be described by their bound name or
// their target), otherwise the deepest subcommand summary found walking
// the expanded argv down the manual tree.
func keyBindingAction(
	manuals map[string]command.Manual, boundArgv, argv []string, prefill bool, xRange string,
) string {
	action := keyBindingOverrideDoc(boundArgv, prefill)
	if action == "" {
		action = keyBindingOverrideDoc(argv, prefill)
	}
	if action == "" {
		action = keyBindingManualSummary(manuals, argv)
	}
	switch {
	case action == "":
		return xRange
	case xRange == "":
		return action
	default:
		return action + " (" + xRange + ")"
	}
}

func keyBindingOverrideDoc(argv []string, prefill bool) string {
	best, bestScore := "", 0
	for _, o := range keyBindingOverrides {
		doc := o.doc
		if prefill {
			doc = o.prefillDoc
		}
		if doc == "" {
			continue
		}
		if score := categoryMatchScore(argv, o.match); score > bestScore {
			best, bestScore = doc, score
		}
	}
	return best
}

func keyBindingManualSummary(manuals map[string]command.Manual, argv []string) string {
	if len(argv) == 0 {
		return ""
	}
	m, ok := manuals[argv[0]]
	if !ok {
		return ""
	}
	action := m.Summary
	for _, arg := range argv[1:] {
		sub, ok := findSubManual(m, arg)
		if !ok {
			break
		}
		if sub.Summary != "" {
			action = sub.Summary
		}
		m = sub
	}
	return action
}

func findSubManual(m command.Manual, name string) (command.Manual, bool) {
	for _, sub := range m.Commands {
		if sub.Name == name {
			return sub, true
		}
	}
	return command.Manual{}, false
}

// mdCode wraps s in a Markdown code span safe for a list entry: specs
// containing backticks (such as the <a-`> key or vi mark sequences)
// get double-backtick delimiters.
func mdCode(s string) string {
	s = mdText(s)
	if strings.Contains(s, "`") {
		return "`` " + s + " ``"
	}
	return "`" + s + "`"
}

// mdBold wraps s in a bold span for a list entry. The markdown
// component honors neither backslash escapes nor HTML entities, and it
// silently drops raw-HTML tags and emphasis markers, so command lines
// such as "echo {prompt}edit<space>" must be neutralized structurally:
// a zero-width space after each inline-significant rune breaks the
// construct (the <...> tag, the *, the _) while staying invisible, so
// the literal command text survives.
func mdBold(s string) string {
	s = mdText(s)
	if s == "" {
		return ""
	}
	var b strings.Builder
	b.WriteString("**")
	for _, r := range s {
		b.WriteRune(r)
		if strings.ContainsRune("<*_[]()&`", r) {
			b.WriteRune('\u200b')
		}
	}
	b.WriteString("**")
	return b.String()
}

// mdText sanitizes s for a single-line Markdown list entry: whitespace
// runs (including newlines in multi-paragraph manual summaries) join
// into single spaces so an entry never spills onto following lines.
func mdText(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
