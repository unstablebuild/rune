// longestPiece is where a stretch is cut: the model reads 2,048 tokens of
// an input at most.
const longestPiece = 4000

// piece is a stretch of a file: its text, and its first and last lines (or
// notebook cells), from 1.
type piece struct {
	text        string
	first, last int
}

// leftOut is why a file is skipped rather than failed: it is not code
// anyone wrote.
type leftOut string

func (e leftOut) Error() string { return string(e) }

// codeFile is a code file cut for indexing.
type codeFile struct {
	pieces []piece
	// title is how the model reads where the file is: its path with the
	// workspace's name first.
	title string
	lines int
	// cells counts a notebook's cells; 0 for anything else.
	cells int
}

// readCode cuts the file data at rel into stretches of stretch characters
// (a notebook into whole cells).
func readCode(data []byte, rel, title string, opts Options) (codeFile, error) {
	if extension(rel) == "ipynb" {
		cells, err := notebookCells(data)
		if err != nil {
			return codeFile{}, err
		}
		text := strings.Join(cells, "\n")
		if int64(len(text)) > opts.MaxCodeBytes {
			return codeFile{}, leftOut(fmt.Sprintf("cells over %d MB", opts.MaxCodeBytes>>20))
		}
		if err := checkCode(text, true); err != nil {
			return codeFile{}, err
		}
		return codeFile{pieces: notebookPieces(cells, opts.CodeStretch), title: title, lines: lineCount(text),
			cells: len(cells)}, nil
	}
	if bytes.IndexByte(data[:min(len(data), 8000)], 0) >= 0 {
		return codeFile{}, leftOut("not text")
	}
	text := string(data)
	if !utf8.Valid(data) {
		runes := make([]rune, len(data))
		for i, b := range data {
			runes[i] = rune(b)
		}
		text = string(runes)
	}
	if err := checkCode(text, sourceExtensions[extension(rel)]); err != nil {
		return codeFile{}, err
	}
	return codeFile{pieces: lines(text, opts.CodeStretch), title: title, lines: lineCount(text)}, nil
}

var generatorMarks = []string{"DO NOT EDIT", "@generated", "Code generated by", "Autogenerated by",
	"Generated by the protocol"}

// checkCode leaves out code that is no use to read: it holds a private
// key, or (source: code, not a repo's docs) a program wrote it or it is
// minified.
func checkCode(text string, source bool) error {
	if strings.Contains(text, "PRIVATE KEY-----") {
		return leftOut("holds a private key")
	}
	if !source {
		return nil
	}
	top := prefixRunes(text, 1000)
	for _, mark := range generatorMarks {
		if strings.Contains(top, mark) {
			return leftOut(fmt.Sprintf("made by a program (“%s”)", mark))
		}
	}
	n, chars := max(1, lineCount(text)), utf8.RuneCountInString(text)
	if chars/n > 300 {
		for line := range strings.SplitSeq(text, "\n") {
			if utf8.RuneCountInString(line) > 3000 {
				return leftOut(fmt.Sprintf("minified (%d characters a line)", chars/n))
			}
		}
	}
	return nil
}

func prefixRunes(s string, n int) string {
	for i := range s {
		if n == 0 {
			return s[:i]
		}
		n--
	}
	return s
}

func lineCount(text string) int {
	n := strings.Count(text, "\n")
	if text == "" || strings.HasSuffix(text, "\n") {
		return n
	}
	return n + 1
}

// splitLines splits on "\n" and "\r\n", as an editor ends lines.
func splitLines(text string) []string {
	out := strings.Split(text, "\n")
	for i := range len(out) - 1 {
		out[i] = strings.TrimSuffix(out[i], "\r")
	}
	return out
}

func isBlank(s string) bool { return strings.TrimFunc(s, unicode.IsSpace) == "" }

func trimSpaces(s string) string { return strings.Trim(s, " \t") }

// closers are lines that close a block (shell, Ruby, Lua, Objective-C, the
// C preprocessor).
var closers = set("end", "fi", "done", "esac", "@end", "#endif", "end;", "end)")

// lines cuts text into stretches of whole lines of at most size characters
// (a longer line is a stretch of its own). A stretch ends, when it can,
// where the code does: before a line that starts a block at the left margin,
// or after a blank line, in its last 60%. One that had to stop inside a
// block hands its last two lines on to the next.
func lines(text string, size int) []piece {
	ls := splitLines(text)
	if ls[len(ls)-1] == "" {
		ls = ls[:len(ls)-1]
	}
	count := len(ls)
	offsets := make([]int, count+1)
	for i, l := range ls {
		offsets[i+1] = offsets[i] + utf8.RuneCountInString(l) + 1
	}
	blank := func(i int) bool { return isBlank(ls[i]) }
	startsBlock := func(i int) bool {
		first, _ := utf8.DecodeRuneInString(ls[i])
		if ls[i] == "" || unicode.IsSpace(first) {
			return false
		}
		return !strings.ContainsRune("})]", first) && !closers[trimSpaces(ls[i])]
	}

	var pieces []piece
	for start := 0; start < count; {
		for start < count && blank(start) {
			start++
		}
		if start >= count {
			break
		}
		end := start + 1
		for end < count && offsets[end+1]-offsets[start] <= size {
			end++
		}
		natural := end >= count
		if !natural {
			floor := offsets[start] + size*2/5
			lastBreak := func(isBreak func(int) bool) int {
				for line := end; line > start+1 && offsets[line] >= floor; line-- {
					if isBreak(line) {
						return line
					}
				}
				return -1
			}
			cut := lastBreak(func(l int) bool { return startsBlock(l) && blank(l-1) })
			if cut < 0 {
				cut = lastBreak(func(l int) bool { return blank(l-1) || startsBlock(l) })
			}
			if cut >= 0 {
				end, natural = cut, true
			}
		}
		last := end
		for last > start+1 && blank(last-1) {
			last--
		}
		body := prefixRunes(strings.Join(ls[start:last], "\n"), longestPiece)
		pieces = append(pieces, piece{text: body, first: start + 1, last: last})
		if natural {
			start = end
		} else {
			start = max(end-2, start+1)
		}
	}
	return pieces
}

// notebookPieces puts whole cells in a stretch, up to size characters; a
// longer cell is cut into stretches of lines that all point at it. Empty
// cells are passed over.
func notebookPieces(cells []string, size int) []piece {
	var pieces []piece
	var text strings.Builder
	first, last := 0, 0
	flush := func() {
		if text.Len() > 0 {
			pieces = append(pieces, piece{text: text.String(), first: first, last: last})
			text.Reset()
		}
	}
	for i, cell := range cells {
		body := strings.TrimSpace(cell)
		if body == "" {
			continue
		}
		number := i + 1
		n := utf8.RuneCountInString(body)
		if n > size {
			flush()
			for _, p := range lines(body, size) {
				pieces = append(pieces, piece{text: p.text, first: number, last: number})
			}
			continue
		}
		if text.Len() > 0 && utf8.RuneCountInString(text.String())+2+n > size {
			flush()
		}
		if text.Len() == 0 {
			first = number
		} else {
			text.WriteString("\n\n")
		}
		text.WriteString(body)
		last = number
	}
	flush()
	return pieces
}

// notebookCells returns the text of a Jupyter notebook's cells, code and
// notes alike; outputs are never read. nbformat 4 keeps its cells at the
// top, nbformat 3 inside worksheets with code in "input".
func notebookCells(data []byte) ([]string, error) {
	var nb struct {
		Cells      []map[string]json.RawMessage `json:"cells"`
		Worksheets []struct {
			Cells []map[string]json.RawMessage `json:"cells"`
		} `json:"worksheets"`
	}
	if err := json.Unmarshal(data, &nb); err != nil {
		return nil, errors.New("not a notebook")
	}
	cells := nb.Cells
	if cells == nil && len(nb.Worksheets) > 0 {
		cells = nb.Worksheets[0].Cells
	}
	out := make([]string, 0, len(cells))
	for _, cell := range cells {
		src, ok := cell["source"]
		if !ok {
			src = cell["input"]
		}
		var parts []string
		var whole string
		switch {
		case json.Unmarshal(src, &parts) == nil:
			whole = strings.Join(parts, "")
		case json.Unmarshal(src, &whole) == nil:
		}
		out = append(out, whole)
	}
	return out, nil
}

var summaryNonCode = []string{"//", "#", "/*", "*", "--", `"""`, "import ", "from ", "#include", "using ", "package ",
	"}", ")", "@"}

// summary is a stretch in one line, for result lists: its first line that
// defines something, else its first line of code.
func summary(text string) string {
	var ls []string
	for _, l := range splitLines(text) {
		if l = trimSpaces(l); l != "" {
			ls = append(ls, l)
		}
	}
	pick := ""
	for _, l := range ls {
		if startsDefinition(l) {
			pick = l
			break
		}
	}
	if pick == "" {
		for _, l := range ls {
			if !hasAnyPrefix(l, summaryNonCode...) {
				pick = l
				break
			}
		}
	}
	if pick == "" && len(ls) > 0 {
		pick = ls[0]
	}
	if utf8.RuneCountInString(pick) > 160 {
		return prefixRunes(pick, 160) + "…"
	}
	return pick
}

// startsDefinition reports a line whose first four words include one that
// defines something.
func startsDefinition(line string) bool {
	words := strings.Fields(line)
	return slices.ContainsFunc(words[:min(4, len(words))], definesSomething)
}

var identifierPattern = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*(?:(?:\.|::|->|#)[A-Za-z_$][A-Za-z0-9_$]*)*$`)

// identifier returns the words keyword search keeps a name from code as
// ("quantize_row_q8_0_ref" → quantize row q8 0 ref), when query is one:
// snake_case, camelCase, dotted, or with digits. It is nil for words anyone
// would say ("retry", "Renamer"), which are searched as words and by
// meaning.
func identifier(query string) []string {
	name := strings.TrimSuffix(strings.TrimSpace(query), "()")
	if !identifierPattern.MatchString(name) {
		return nil
	}
	camel := strings.ContainsFunc(name[1:], unicode.IsUpper) && strings.ContainsFunc(name, unicode.IsLower)
	if !camel && !strings.ContainsAny(name, "_.:#$0123456789") {
		return nil
	}
	return strings.FieldsFunc(strings.ToLower(name), func(r rune) bool { return !isAlphanumeric(r) })
}

// identifierPhrase is the keyword phrase for an identifier's words: one
// phrase, so they match only side by side, as written.
func identifierPhrase(words []string) phrase { return newPhrase(strings.Join(words, " "), false) }

var (
	definers = set("def", "func", "fn", "fun", "function", "class", "struct", "enum", "protocol", "interface", "trait",
		"type", "typealias", "actor", "extension", "impl", "module", "namespace", "object", "record", "macro", "const",
		"let", "var", "val", "union", "mod", "sub", "@interface", "@implementation", "@protocol", "#define", "function*")
	// users are words before a name that mean it is being used, not
	// defined ("return name(…)").
	users = set("return", "await", "yield", "throw", "new", "else", "case", "print", "echo", "assert", "not", "and",
		"or", "in", "is", "do", "go", "defer", "try", "catch", "if", "while", "for", "typeof", "delete", "raise",
		"import", "from")
	commentStarts = []string{"//", "#", "/*", "*", "--", `"""`, "'''", "<!--", ";"}
)

// definesSomething reports a word that starts a definition ("def", "func",
// "class"…), not a variable.
func definesSomething(word string) bool {
	return definers[word] && word != "let" && word != "var" && word != "const" && word != "val"
}

// definition finds where name is defined in text, a stretch whose first
// line is first: the line and how surely. Strength 2 follows a word that
// defines something or is a C-style definition; 1 is a declaration (the
// same, ending in ";"). ok is false when the stretch only uses name.
func definition(name, text string, first int) (line, strength int, ok bool) {
	for offset, l := range splitLines(text) {
		for _, at := range occurrences(name, l) {
			before, after := trimSpaces(l[:at]), trimSpaces(l[at+len(name):])
			if s := definitionStrength(before, after, l); s > strength {
				line, strength, ok = first+offset, s, true
				if s == 2 {
					return line, strength, ok
				}
			}
		}
	}
	return line, strength, ok
}

func definitionStrength(before, after, line string) int {
	words := strings.Fields(before)
	previous := ""
	if len(words) > 0 {
		previous = words[len(words)-1]
	}
	switch {
	case definers[previous]:
		return 2
	case strings.HasPrefix(before, "func (") && strings.HasSuffix(before, ")"):
		return 2
	case strings.HasPrefix(before, "- (") || strings.HasPrefix(before, "+ ("):
		if after == "" || hasAnyPrefix(after, ":", "{", ";") {
			return 2
		}
		return 0
	}
	if !strings.HasPrefix(after, "(") || before == "" || users[previous] || strings.ContainsAny(before, "=(,.!?") ||
		strings.Contains(before, "->") {
		return 0
	}
	last, _ := utf8.DecodeLastRuneInString(before)
	if !unicode.IsLetter(last) && !unicode.IsNumber(last) && !strings.ContainsRune("*&>_]", last) {
		return 0
	}
	if strings.HasSuffix(trimSpaces(line), ";") {
		return 1
	}
	return 2
}

// occurrences returns the byte offsets where name is in line as a whole
// name, whatever its case. name is ASCII (identifierPattern).
func occurrences(name, line string) []int {
	var found []int
	for i := 0; i+len(name) <= len(line); i++ {
		if !asciiEqualFold(line[i:i+len(name)], name) {
			continue
		}
		clearBefore := i == 0 || !isNameCharacter(lastRune(line[:i]))
		r, _ := utf8.DecodeRuneInString(line[i+len(name):])
		clearAfter := i+len(name) == len(line) || !isNameCharacter(r)
		if clearBefore && clearAfter {
			found = append(found, i)
		}
		i += len(name) - 1
	}
	return found
}

func asciiEqualFold(a, b string) bool {
	for i := range len(a) {
		x, y := a[i], b[i]
		if 'A' <= x && x <= 'Z' {
			x += 'a' - 'A'
		}
		if 'A' <= y && y <= 'Z' {
			y += 'a' - 'A'
		}
		if x != y {
			return false
		}
	}
	return true
}

func lastRune(s string) rune {
	r, _ := utf8.DecodeLastRuneInString(s)
	return r
}

func isNameCharacter(r rune) bool {
	return unicode.IsLetter(r) || unicode.IsNumber(r) || r == '_' || r == '$'
}

// firstLine returns the line (from first) to open text at for words: the
// first line with one of them that defines something, else the first such
// line of code (not a comment), else the first such line. A word counts as
// itself or as a part of a name (the "retry" of retryWithBackoff). ok is
// false when none is there.
func firstLine(words []string, text string, first int) (int, bool) {
	var want [][]rune
	for _, w := range words {
		if utf8.RuneCountInString(w) >= 2 {
			want = append(want, lowerRunes(w))
		}
	}
	if len(want) == 0 {
		return 0, false
	}
	firstCode, firstAny := -1, -1
	for offset, l := range splitLines(text) {
		if !hasAnyWord(want, l) {
			continue
		}
		trimmed := trimSpaces(l)
		if startsDefinition(trimmed) {
			return first + offset, true
		}
		if firstCode < 0 && !hasAnyPrefix(trimmed, commentStarts...) {
			firstCode = offset
		}
		if firstAny < 0 {
			firstAny = offset
		}
	}
	switch {
	case firstCode >= 0:
		return first + firstCode, true
	case firstAny >= 0:
		return first + firstAny, true
	}
	return 0, false
}

func lowerRunes(s string) []rune {
	r := []rune(s)
	for i := range r {
		r[i] = unicode.ToLower(r[i])
	}
	return r
}

func hasAnyWord(words [][]rune, line string) bool {
	orig := []rune(line)
	lower := lowerRunes(line)
	for _, w := range words {
		if hasWord(w, orig, lower) {
			return true
		}
	}
	return false
}

// hasWord reports whether word (lower case) is in the line as a word or as
// the start of a name's part: at the line's start, after something that is
// not a letter or digit, or at a capital letter (camelCase).
func hasWord(word, orig, lower []rune) bool {
	for i := 0; i+len(word) <= len(lower); i++ {
		if string(lower[i:i+len(word)]) != string(word) {
			continue
		}
		if i == 0 || (!unicode.IsLetter(lower[i-1]) && !unicode.IsNumber(lower[i-1])) || unicode.IsUpper(orig[i]) {
			return true
		}
	}
	return false
}
