import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {homedir} from 'node:os';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {dump, load} from 'js-yaml';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const docsRoot = resolve(scriptDir, '..');
const runeRoot = resolve(
  process.env.RUNE_REPO ?? join(homedir(), 'src', 'rune'),
);
const outputPath = join(docsRoot, 'src', 'data', 'keybindings.yaml');

// Docs preset ids mapped to the editor name in cmd/rune/preset_<editor>_<os>.yaml.
const editors = {
  modal: 'vim',
  helix: 'helix',
  standard: 'standard',
  emacs: 'emacs',
};
const platforms = ['darwin', 'linux'];

function isObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

async function readPreset(relativePath, fallbackCommandKey) {
  const sourcePath = join(runeRoot, relativePath);
  let contents;
  try {
    contents = await readFile(sourcePath, 'utf8');
  } catch (error) {
    throw new Error(`Cannot read Rune preset ${sourcePath}: ${error.message}`);
  }

  const config = load(contents);
  const commandKey = config?.command?.key ?? fallbackCommandKey;
  const keybindings = config?.command?.key_bindings;
  if (typeof commandKey !== 'string') {
    throw new Error(`${sourcePath} has an invalid command.key value`);
  }
  if (!isObject(keybindings)) {
    throw new Error(`${sourcePath} has no command.key_bindings mapping`);
  }

  for (const [key, commands] of Object.entries(keybindings)) {
    const valid =
      typeof commands === 'string' ||
      (Array.isArray(commands) && commands.every((command) => typeof command === 'string'));
    if (!valid) {
      throw new Error(
        `${sourcePath} has an invalid command.key_bindings value for ${key}`,
      );
    }
  }

  return {command_key: commandKey, key_bindings: keybindings};
}

const keybindings = {};
for (const [preset, editor] of Object.entries(editors)) {
  keybindings[preset] = {};
  for (const platform of platforms) {
    keybindings[preset][platform] = await readPreset(
      `cmd/rune/preset_${editor}_${platform}.yaml`,
      ':',
    );
  }
}

const header = [
  '# Generated by `npm run keybindings`. Do not edit by hand.',
  '# Source: cmd/rune/preset_*.yaml in the Rune repository.',
  '# Contains only command.key and command.key_bindings from each Rune editor preset.',
  '',
].join('\n');

const yaml = dump(keybindings, {
  lineWidth: -1,
  noRefs: true,
  quotingType: '"',
});

await mkdir(dirname(outputPath), {recursive: true});
await writeFile(outputPath, header + yaml, 'utf8');
console.log(`Wrote ${outputPath}`);
